"""Compile runtime/src/gpu/vk/post.comp to post_spv.h (SPIR-V words). Needs glslc (Vulkan SDK) on PATH
or in %VULKAN_SDK%\Bin; the build itself only uses the checked-in header.

    python tools/compile_post.py
"""
import glob
import os
import shutil
import struct
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "runtime", "src", "gpu", "vk", "post.comp")
OUT = os.path.join(ROOT, "runtime", "src", "gpu", "vk", "post_spv.h")


def find_glslc():
    g = shutil.which("glslc")
    if g:
        return g
    cands = []
    if os.environ.get("VULKAN_SDK"):
        cands.append(os.path.join(os.environ["VULKAN_SDK"], "Bin", "glslc.exe"))
    cands += sorted(glob.glob(r"C:\VulkanSDK\*\Bin\glslc.exe"), reverse=True)
    for c in cands:
        if os.path.exists(c):
            return c
    sys.exit("glslc not found: install the Vulkan SDK")


def main():
    with tempfile.TemporaryDirectory() as d:
        spv = os.path.join(d, "post.spv")
        subprocess.check_call([find_glslc(), "-O", "--target-env=vulkan1.2", SRC, "-o", spv])
        data = open(spv, "rb").read()
    words = struct.unpack(f"<{len(data) // 4}I", data)
    lines = ["// Generated by tools/compile_post.py from post.comp. Do not edit.", "#pragma once", "",
             f"static const unsigned int kPostSpv[{len(words)}] = {{"]
    for i in range(0, len(words), 8):
        lines.append("    " + ", ".join(f"0x{w:08x}" for w in words[i:i + 8]) + ",")
    lines.append("};")
    open(OUT, "w", newline="\n").write("\n".join(lines) + "\n")
    print(f"{OUT}: {len(words)} words")


if __name__ == "__main__":
    main()
